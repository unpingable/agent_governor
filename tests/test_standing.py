class TestWorkloadIdSerialization:
    def test_from_dict_roundtrip(self):
        token = _load_fixture("fixture_good.json")
        d = token.to_dict()
        token2 = WorkloadId.from_dict(d)
        assert token2.jti == token.jti
        assert token2.signature == token.signature

    def test_from_json(self):
        text = (FIXTURES / "fixture_good.json").read_text()
        token = WorkloadId.from_json(text)
        assert token.name == "test-bot"
