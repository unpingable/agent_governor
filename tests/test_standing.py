class TestSyntheticTokens:
    def _make_token(self, **overrides) -> WorkloadId:
        now = datetime.now(timezone.utc)
        defaults = {
            "jti": "test-jti-123",
            "name": "bot",
            "location": "host-1",
            "audience": "standing",
            "issued_at": now.isoformat(),
            "expires_at": (now + timedelta(hours=1)).isoformat(),
        }
        defaults.update(overrides)
        sig = _compute_signature(
            defaults["jti"], defaults["name"], defaults["location"],
            defaults["audience"], defaults["issued_at"], defaults["expires_at"],
            SECRET,
        )
        defaults["signature"] = sig
        return WorkloadId(**defaults)

    def test_synthetic_valid(self):
        token = self._make_token()
        result = verify_identity(token, SECRET)
        assert result == AssessmentResult.VALID

    def test_temporal_incoherence_compromised(self):
        """expires_at before issued_at → compromised."""
        now = datetime.now(timezone.utc)
        token = self._make_token(
            issued_at=now.isoformat(),
            expires_at=(now - timedelta(hours=1)).isoformat(),
        )
        result = verify_identity(token, SECRET)
        assert result == AssessmentResult.ASSESSMENT_COMPROMISED

    def test_principal_id_format(self):
        token = self._make_token(name="deploy-bot", location="k8s-prod")
        assert token.principal_id == "wl:deploy-bot:k8s-prod"


