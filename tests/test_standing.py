class TestCrossLanguageSignature:
    def test_good_fixture_signature_matches(self):
        """Python computes the same signature as Rust for the good fixture."""
        token = _load_fixture("fixture_good.json")
        sig = _compute_signature(
            token.jti, token.name, token.location, token.audience,
            token.issued_at, token.expires_at, SECRET,
        )
        assert sig == token.signature

    def test_bad_aud_fixture_signature_matches(self):
        """Signature is valid even for wrong-audience tokens (signature is over all fields)."""
        token = _load_fixture("fixture_bad_aud.json")
        sig = _compute_signature(
            token.jti, token.name, token.location, token.audience,
            token.issued_at, token.expires_at, SECRET,
        )
        assert sig == token.signature

    def test_short_ttl_fixture_signature_matches(self):
        token = _load_fixture("fixture_short_ttl.json")
        sig = _compute_signature(
            token.jti, token.name, token.location, token.audience,
            token.issued_at, token.expires_at, SECRET,
        )
        assert sig == token.signature


