class TestVerifyAndResolve:
    def test_returns_verified_identity(self):
        token = _load_fixture("fixture_good.json")
        vi = verify_and_resolve(token, SECRET, now=_issued_time(token))
        assert isinstance(vi, VerifiedIdentity)
        assert vi.principal_id == "wl:test-bot:host-1"
        assert vi.label == "test-bot"
        assert vi.audience == "standing"
        assert vi.jti == token.jti

    def test_fails_closed_on_bad_signature(self):
        token = _load_fixture("fixture_good.json")
        with pytest.raises(StandingVerificationError) as exc_info:
            verify_and_resolve(token, b"wrong", now=_issued_time(token))
        assert exc_info.value.result == AssessmentResult.INVALID_SIGNATURE

    def test_fails_closed_on_expired(self):
        token = _load_fixture("fixture_short_ttl.json")
        future = _issued_time(token) + timedelta(seconds=60)
        with pytest.raises(StandingVerificationError) as exc_info:
            verify_and_resolve(token, SECRET, now=future)
        assert exc_info.value.result == AssessmentResult.EXPIRED


