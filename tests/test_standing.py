"""Tests for standing identity verification.

Cross-language conformance: fixtures are generated by the Rust standing-cli
(`standing identity create`). Python must produce identical verification
results for the same inputs.
"""

from __future__ import annotations

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

from governor.standing.workload_identity import (
    AssessmentResult,
    StandingVerificationError,
    VerifiedIdentity,
    WorkloadId,
    _compute_signature,
    _to_rfc3339_signing,
    verify_and_resolve,
    verify_identity,
)

FIXTURES = Path(__file__).parent / "fixtures" / "standing"
SECRET = b"test-secret"


def _load_fixture(name: str) -> WorkloadId:
    data = json.loads((FIXTURES / name).read_text())
    return WorkloadId.from_dict(data)


def _issued_time(token: WorkloadId) -> datetime:
    """Parse issued_at to use as 'now' for expired tokens."""
    ts = token.issued_at.replace("Z", "+00:00")
    return datetime.fromisoformat(ts)


# ---------------------------------------------------------------------------
# Canonicalization
# ---------------------------------------------------------------------------

class TestCanonicalization:
    def test_z_to_plus_zero(self):
        assert _to_rfc3339_signing("2026-01-01T00:00:00Z") == "2026-01-01T00:00:00+00:00"

    def test_plus_zero_unchanged(self):
        assert _to_rfc3339_signing("2026-01-01T00:00:00+00:00") == "2026-01-01T00:00:00+00:00"

    def test_nanoseconds_preserved(self):
        assert _to_rfc3339_signing("2026-04-07T21:07:25.247857573Z") == "2026-04-07T21:07:25.247857573+00:00"


