class TestVerifyIdentity:
    def test_good_fixture_valid(self):
        token = _load_fixture("fixture_good.json")
        result = verify_identity(token, SECRET, now=_issued_time(token))
        assert result == AssessmentResult.VALID

    def test_wrong_secret_invalid_signature(self):
        token = _load_fixture("fixture_good.json")
        result = verify_identity(token, b"wrong", now=_issued_time(token))
        assert result == AssessmentResult.INVALID_SIGNATURE

    def test_tampered_name_invalid_signature(self):
        token = _load_fixture("fixture_good.json")
        token.name = "evil"
        result = verify_identity(token, SECRET, now=_issued_time(token))
        assert result == AssessmentResult.INVALID_SIGNATURE

    def test_wrong_audience_mismatch(self):
        token = _load_fixture("fixture_bad_aud.json")
        result = verify_identity(
            token, SECRET,
            expected_audience="standing",
            now=_issued_time(token),
        )
        assert result == AssessmentResult.AUDIENCE_MISMATCH

    def test_correct_audience_accepted(self):
        token = _load_fixture("fixture_bad_aud.json")
        result = verify_identity(
            token, SECRET,
            expected_audience="wrong-aud",
            now=_issued_time(token),
        )
        assert result == AssessmentResult.VALID

    def test_expired_token_rejected(self):
        token = _load_fixture("fixture_short_ttl.json")
        # 60s in the future, well past 1s TTL + 30s skew
        future = _issued_time(token) + timedelta(seconds=60)
        result = verify_identity(token, SECRET, now=future)
        assert result == AssessmentResult.EXPIRED

    def test_within_skew_accepted(self):
        token = _load_fixture("fixture_short_ttl.json")
        # 2s after issuance — past 1s TTL but within 30s skew
        near = _issued_time(token) + timedelta(seconds=2)
        result = verify_identity(token, SECRET, now=near)
        assert result == AssessmentResult.VALID

    def test_not_yet_valid(self):
        token = _load_fixture("fixture_good.json")
        # Verify from 60s in the past (beyond 30s skew)
        past = _issued_time(token) - timedelta(seconds=60)
        result = verify_identity(token, SECRET, now=past)
        assert result == AssessmentResult.NOT_YET_VALID

    def test_clock_divergence_compromised(self):
        token = _load_fixture("fixture_good.json")
        # Verifier 10 min behind issuer (beyond 300s max divergence)
        way_past = _issued_time(token) - timedelta(seconds=601)
        result = verify_identity(token, SECRET, now=way_past)
        assert result == AssessmentResult.ASSESSMENT_COMPROMISED

    def test_extreme_divergence_but_clearly_expired(self):
        token = _load_fixture("fixture_short_ttl.json")
        # Way in the future, clearly expired even under divergence
        way_future = _issued_time(token) + timedelta(seconds=1200)
        result = verify_identity(token, SECRET, now=way_future)
        assert result == AssessmentResult.EXPIRED


